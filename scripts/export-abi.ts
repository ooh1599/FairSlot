/** Writes shared/fairslotAbi.ts from the Foundry artifact. Run after `forge build` whenever FairSlot.sol changes. */
import { readFileSync, writeFileSync } from 'node:fs'

const artifact = JSON.parse(readFileSync(new URL('../contracts/out/FairSlot.sol/FairSlot.json', import.meta.url), 'utf8')) as { abi: unknown[] }
const abi = artifact.abi
const body = `// Generated by scripts/export-abi.ts from contracts/out/FairSlot.sol/FairSlot.json. Do not edit.\nexport const fairSlotAbi = ${JSON.stringify(abi, null, 2)} as const\n`
writeFileSync(new URL('../shared/fairslotAbi.ts', import.meta.url), body)
console.log(`wrote ${abi.length} ABI entries`)
