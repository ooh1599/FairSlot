/** Prints golden draw vectors as JSON (docs/golden-vectors.json) and as Solidity constants. */
import { writeFileSync } from 'node:fs'
import { computeWinners, drawBase } from '../shared/draw'
import {
  VECTOR_CASES,
  VECTOR_CHAIN_ID,
  VECTOR_CONTRACT,
  VECTOR_EVENT_ID,
  VECTOR_FIRST_REQUEST_ID,
  VECTOR_MANIFEST_HASH,
  VECTOR_WORD,
} from '../shared/vectors'

const out = VECTOR_CASES.map((c, i) => {
  const requestId = VECTOR_FIRST_REQUEST_ID + BigInt(i)
  const input = {
    chainId: VECTOR_CHAIN_ID,
    contract: VECTOR_CONTRACT,
    eventId: VECTOR_EVENT_ID,
    manifestHash: VECTOR_MANIFEST_HASH,
    requestId,
    randomWord: VECTOR_WORD,
    participantCount: c.participants,
    winnerCount: c.winners,
    reserveCount: c.reserves,
  }
  return {
    name: c.name,
    requestId: requestId.toString(),
    participants: c.participants,
    winners: c.winners,
    reserves: c.reserves,
    drawBase: drawBase(input),
    result: computeWinners(input),
  }
})

writeFileSync(
  new URL('../docs/golden-vectors.json', import.meta.url),
  JSON.stringify(
    {
      note: 'Generated by scripts/gen-vectors.ts. Solidity and TypeScript must both reproduce these.',
      chainId: VECTOR_CHAIN_ID.toString(),
      contract: VECTOR_CONTRACT,
      eventId: VECTOR_EVENT_ID,
      manifestHash: VECTOR_MANIFEST_HASH,
      randomWord: VECTOR_WORD,
      cases: out,
    },
    null,
    2,
  ) + '\n',
)
console.log(`eventId ${VECTOR_EVENT_ID}`)
for (const c of out) console.log(c.name, c.result.join(','))
