create or replace function public.public_event(p_public_id text)
returns table (
  public_id text, title text, description text, rules text, prizes jsonb,
  winner_count int, reserve_count int, draw_not_before timestamptz, status public.event_status,
  chain_id int, contract_address text, organizer_wallet text, manifest_hash text, manifest_uri text,
  commit_tx_hash text, onchain_event_id text, locked_at timestamptz, committed_at timestamptz
)
language sql stable security definer set search_path = public as $$
  select e.public_id, e.title, e.description, e.rules, e.prizes, e.winner_count, e.reserve_count,
         e.draw_not_before, e.status, e.chain_id, e.contract_address, e.organizer_wallet, e.manifest_hash,
         e.manifest_uri, e.commit_tx_hash, e.onchain_event_id, e.locked_at, e.committed_at
  from public.events e
  where e.public_id = p_public_id and e.status <> 'draft';
$$;

create or replace function public.public_delivery(p_public_id text)
returns table (public_entry_id text, rank int, status public.delivery_status, updated_at timestamptz)
language sql stable security definer set search_path = public as $$
  select en.public_entry_id, f.rank, f.status, f.updated_at
  from public.events e
  join public.winner_followups f on f.event_id = e.id
  join public.entries en on en.id = f.entry_id
  where e.public_id = p_public_id and e.status = 'committed'
  order by f.rank;
$$;

revoke all on function public.public_event(text), public.public_delivery(text) from public;
grant execute on function public.public_event(text), public.public_delivery(text) to anon, authenticated;

