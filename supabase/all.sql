-- FairSlot schema. Private participant data lives here behind Row Level Security.
-- Public pages only ever read through the security-definer functions at the bottom.

create extension if not exists pgcrypto;

create type public.event_status as enum ('draft', 'locked', 'committed');
create type public.delivery_status as enum ('pending', 'contacted', 'confirmed', 'delivered', 'declined', 'no_response');

-- ---------------------------------------------------------------------------------------------
-- Random public entry IDs: 60 random bits, Crockford base32, e.g. 7K3M-9QX2-H4TD.
-- Generated by the database so an organizer cannot pick or grind IDs.
-- ---------------------------------------------------------------------------------------------
create or replace function public.fs_random_entry_id() returns text
language plpgsql volatile as $$
declare
  alphabet constant text := '0123456789ABCDEFGHJKMNPQRSTVWXYZ';
  b bytea := gen_random_bytes(12);
  s text := '';
  i int;
begin
  for i in 0..11 loop
    s := s || substr(alphabet, (get_byte(b, i) & 31) + 1, 1);
    if i in (3, 7) then s := s || '-'; end if;
  end loop;
  return s;
end $$;

-- ---------------------------------------------------------------------------------------------
-- Events
-- ---------------------------------------------------------------------------------------------
create table public.events (
  id uuid primary key default gen_random_uuid(),
  public_id text not null unique check (public_id ~ '^fs_[0-9a-hjkmnp-tv-z]{20}$'),
  organizer_id uuid not null references auth.users (id) on delete restrict,
  title text not null check (char_length(title) between 1 and 120),
  description text not null default '' check (char_length(description) <= 2000),
  rules text not null default '' check (char_length(rules) <= 4000),
  prizes jsonb not null default '[]'::jsonb check (jsonb_typeof(prizes) = 'array'),
  winner_count int not null default 1 check (winner_count between 1 and 50),
  reserve_count int not null default 0 check (reserve_count between 0 and 49),
  draw_not_before timestamptz not null,
  status public.event_status not null default 'draft',
  -- everything below is written by the server only (service role) when the event is locked / committed
  chain_id int,
  contract_address text,
  organizer_wallet text,
  manifest_hash text,
  manifest_path text,
  manifest_uri text,
  locked_at timestamptz,
  commit_tx_hash text,
  onchain_event_id text,
  committed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint picks_limit check (winner_count + reserve_count <= 50)
);
create index events_organizer_idx on public.events (organizer_id, created_at desc);

-- Content columns can never change after the event leaves draft; system columns are write-once.
create or replace function public.events_guard() returns trigger
language plpgsql as $$
begin
  if tg_op = 'DELETE' then
    if old.status <> 'draft' then
      raise exception 'locked events cannot be deleted' using errcode = 'P0001';
    end if;
    return old;
  end if;
  new.updated_at := now();
  if old.status <> 'draft' then
    if new.public_id is distinct from old.public_id
      or new.organizer_id is distinct from old.organizer_id
      or new.title is distinct from old.title
      or new.description is distinct from old.description
      or new.rules is distinct from old.rules
      or new.prizes is distinct from old.prizes
      or new.winner_count is distinct from old.winner_count
      or new.reserve_count is distinct from old.reserve_count
      or new.draw_not_before is distinct from old.draw_not_before then
      raise exception 'locked events cannot change; create a new event instead' using errcode = 'P0001';
    end if;
    if (old.manifest_hash is not null and new.manifest_hash is distinct from old.manifest_hash)
      or (old.manifest_uri is not null and new.manifest_uri is distinct from old.manifest_uri)
      or (old.chain_id is not null and new.chain_id is distinct from old.chain_id)
      or (old.contract_address is not null and new.contract_address is distinct from old.contract_address)
      or (old.organizer_wallet is not null and new.organizer_wallet is distinct from old.organizer_wallet)
      or (old.commit_tx_hash is not null and new.commit_tx_hash is distinct from old.commit_tx_hash)
      or (old.onchain_event_id is not null and new.onchain_event_id is distinct from old.onchain_event_id) then
      raise exception 'locked event commitments are write-once' using errcode = 'P0001';
    end if;
    if new.status < old.status then
      raise exception 'event status cannot move backwards' using errcode = 'P0001';
    end if;
  end if;
  return new;
end $$;
create trigger events_guard_trg before update or delete on public.events
  for each row execute function public.events_guard();

-- ---------------------------------------------------------------------------------------------
-- Entries (private mapping between a public entry ID and the real person)
-- ---------------------------------------------------------------------------------------------
create table public.entries (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events (id) on delete cascade,
  public_entry_id text not null default public.fs_random_entry_id(),
  external_id text not null check (char_length(external_id) between 1 and 120),
  display_name text not null check (char_length(display_name) between 1 and 120),
  email text check (email is null or char_length(email) <= 254),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (event_id, public_entry_id),
  unique (event_id, external_id)
);
create index entries_event_idx on public.entries (event_id);

create or replace function public.entries_guard() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  ev uuid;
  st public.event_status;
begin
  ev := case when tg_op = 'DELETE' then old.event_id else new.event_id end;
  select status into st from public.events where id = ev;
  if st is distinct from 'draft' then
    raise exception 'the participant list is locked' using errcode = 'P0001';
  end if;
  if tg_op = 'UPDATE' then
    if new.event_id is distinct from old.event_id or new.public_entry_id is distinct from old.public_entry_id then
      raise exception 'event and public entry id are immutable' using errcode = 'P0001';
    end if;
    new.updated_at := now();
  end if;
  return case when tg_op = 'DELETE' then old else new end;
end $$;
create trigger entries_guard_trg before insert or update or delete on public.entries
  for each row execute function public.entries_guard();

-- Participant cap (10,000) checked once per statement, not once per row.
create or replace function public.entries_cap() returns trigger
language plpgsql as $$
begin
  if exists (
    select 1 from public.entries e
    where e.event_id in (select distinct event_id from inserted)
    group by e.event_id having count(*) > 10000
  ) then
    raise exception 'an event can have at most 10000 participants' using errcode = 'P0001';
  end if;
  return null;
end $$;
create trigger entries_cap_trg after insert on public.entries
  referencing new table as inserted for each statement execute function public.entries_cap();

-- ---------------------------------------------------------------------------------------------
-- Audit log (no personal data: only public entry IDs and counts)
-- ---------------------------------------------------------------------------------------------
create table public.audit_log (
  id bigint generated always as identity primary key,
  event_id uuid not null references public.events (id) on delete cascade,
  actor uuid,
  action text not null,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index audit_event_idx on public.audit_log (event_id, id);

create or replace function public.audit_entries_import() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.audit_log (event_id, actor, action, detail)
  select event_id, auth.uid(), 'entries_added', jsonb_build_object('count', count(*))
  from inserted group by event_id;
  return null;
end $$;
create trigger audit_entries_import_trg after insert on public.entries
  referencing new table as inserted for each statement execute function public.audit_entries_import();

create or replace function public.audit_entries_change() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'DELETE' then
    insert into public.audit_log (event_id, actor, action, detail)
    values (old.event_id, auth.uid(), 'entry_removed', jsonb_build_object('publicEntryId', old.public_entry_id));
    return old;
  end if;
  insert into public.audit_log (event_id, actor, action, detail)
  values (new.event_id, auth.uid(), 'entry_edited', jsonb_build_object(
    'publicEntryId', new.public_entry_id,
    'fields', to_jsonb(array_remove(array[
      case when new.display_name is distinct from old.display_name then 'display_name' end,
      case when new.email is distinct from old.email then 'email' end,
      case when new.external_id is distinct from old.external_id then 'external_id' end
    ], null))));
  return new;
end $$;
create trigger audit_entries_change_trg after update or delete on public.entries
  for each row execute function public.audit_entries_change();

create or replace function public.audit_event_status() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.status is distinct from old.status then
    insert into public.audit_log (event_id, actor, action, detail)
    values (new.id, auth.uid(), 'status_' || new.status::text,
      jsonb_build_object('manifestHash', new.manifest_hash, 'txHash', new.commit_tx_hash));
  end if;
  return null;
end $$;
create trigger audit_event_status_trg after update on public.events
  for each row execute function public.audit_event_status();

